<?php

/**
 * Generates src/Ingest/Schema/table_map.php from db/migrations/*.sql.
 *
 * Ingest maps each record's data fields to the columns of its table (M-010:
 * columns use the agent's field names). This reads the CREATE TABLE statements
 * so the map can't drift from the migrations by hand; the integration test
 * TableMapMatchesDatabaseTest checks it against information_schema on the VM.
 *
 * Run after adding a migration:  php tools/gen-table-map.php
 * A migration that ALTERs a table stops the generator; extend it first.
 * MS-DAT-01.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$files = glob($root . '/db/migrations/*.sql');
sort($files);

$tables = [];
foreach ($files as $file) {
    $sql = (string) file_get_contents($file);
    if (preg_match('/^\s*ALTER\s+TABLE/im', $sql)) {
        fwrite(STDERR, basename($file) . ": ALTER TABLE found; teach gen-table-map.php about it first\n");
        exit(1);
    }
    foreach (createStatements($sql) as [$name, $body]) {
        $tables[$name] = parseBody($body);
    }
}
ksort($tables);

$out = "<?php\n\n// Generated by tools/gen-table-map.php from db/migrations. Do not edit.\n"
    . "// Columns per table: type, length, unsigned, nullable, has_default, enum values, generated.\n\n"
    . "declare(strict_types=1);\n\nreturn " . exportArray($tables) . ";\n";
$target = $root . '/src/Ingest/Schema/table_map.php';
@mkdir(dirname($target), 0755, true);
file_put_contents($target, $out);
fwrite(STDOUT, 'wrote ' . count($tables) . " tables to src/Ingest/Schema/table_map.php\n");

/** @return list<array{0:string,1:string}> */
function createStatements(string $sql): array
{
    $sql = stripComments($sql);
    $out = [];
    $offset = 0;
    while (preg_match('/CREATE\s+TABLE\s+`?(\w+)`?\s*\(/i', $sql, $m, PREG_OFFSET_CAPTURE, $offset)) {
        $start = $m[0][1] + strlen($m[0][0]);
        $depth = 1;
        $i = $start;
        $len = strlen($sql);
        $quote = null;
        for (; $i < $len && $depth > 0; $i++) {
            $c = $sql[$i];
            if ($quote !== null) {
                if ($c === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($c === "'" || $c === '"') {
                $quote = $c;
            } elseif ($c === '(') {
                $depth++;
            } elseif ($c === ')') {
                $depth--;
            }
        }
        $out[] = [$m[1][0], substr($sql, $start, $i - $start - 1)];
        $offset = $i;
    }
    return $out;
}

function stripComments(string $sql): string
{
    $out = '';
    $quote = null;
    $len = strlen($sql);
    for ($i = 0; $i < $len; $i++) {
        $c = $sql[$i];
        if ($quote !== null) {
            $out .= $c;
            if ($c === $quote) {
                $quote = null;
            }
            continue;
        }
        if ($c === "'" || $c === '"') {
            $quote = $c;
            $out .= $c;
            continue;
        }
        if ($c === '-' && ($sql[$i + 1] ?? '') === '-') {
            while ($i < $len && $sql[$i] !== "\n") {
                $i++;
            }
            $out .= "\n";
            continue;
        }
        $out .= $c;
    }
    return $out;
}

/** @return list<string> */
function splitTopLevel(string $body): array
{
    $parts = [];
    $depth = 0;
    $quote = null;
    $cur = '';
    $len = strlen($body);
    for ($i = 0; $i < $len; $i++) {
        $c = $body[$i];
        if ($quote !== null) {
            $cur .= $c;
            if ($c === $quote) {
                $quote = null;
            }
            continue;
        }
        if ($c === "'" || $c === '"') {
            $quote = $c;
        } elseif ($c === '(') {
            $depth++;
        } elseif ($c === ')') {
            $depth--;
        } elseif ($c === ',' && $depth === 0) {
            $parts[] = trim($cur);
            $cur = '';
            continue;
        }
        $cur .= $c;
    }
    if (trim($cur) !== '') {
        $parts[] = trim($cur);
    }
    return $parts;
}

/** @return array{columns: array<string, array<string, mixed>>} */
function parseBody(string $body): array
{
    $columns = [];
    foreach (splitTopLevel($body) as $item) {
        $item = preg_replace('/\s+/', ' ', $item);
        if (preg_match('/^(PRIMARY|UNIQUE|KEY|INDEX|CONSTRAINT|FOREIGN|FULLTEXT|CHECK)\b/i', $item)) {
            continue;
        }
        if (!preg_match('/^`?(\w+)`? (\w+)(?:\(([^)]*)\))?(.*)$/', $item, $m)) {
            throw new RuntimeException("can't parse column: $item");
        }
        [, $name, $type, $args, $rest] = $m;
        $type = strtolower($type);
        $col = [
            'type' => $type,
            'length' => null,
            'unsigned' => (bool) preg_match('/\bUNSIGNED\b/i', $rest),
            'nullable' => !preg_match('/\bNOT NULL\b/i', $rest) && !preg_match('/\bPRIMARY KEY\b/i', $rest),
            'has_default' => (bool) preg_match('/\b(DEFAULT|AUTO_INCREMENT)\b/i', $rest),
            'generated' => (bool) preg_match('/^\s*(?:\w+\s+)*AS \(/i', $rest),
            'enum' => null,
        ];
        if ($type === 'enum') {
            preg_match_all("/'([^']*)'/", $args, $em);
            $col['enum'] = $em[1];
        } elseif ($args !== '' && in_array($type, ['varchar', 'char', 'varbinary', 'binary'], true)) {
            $col['length'] = (int) $args;
        }
        if ($type === 'boolean') {
            $col['type'] = 'bool';
        }
        $columns[$name] = $col;
    }
    return ['columns' => $columns];
}

function exportArray(mixed $v, int $indent = 0): string
{
    if (!is_array($v)) {
        return var_export($v, true);
    }
    $pad = str_repeat('    ', $indent + 1);
    $isList = array_is_list($v);
    $lines = [];
    foreach ($v as $k => $item) {
        $lines[] = $pad . ($isList ? '' : var_export($k, true) . ' => ') . exportArray($item, $indent + 1) . ',';
    }
    return $lines === [] ? '[]' : "[\n" . implode("\n", $lines) . "\n" . str_repeat('    ', $indent) . ']';
}
